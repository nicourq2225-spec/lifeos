export async function ensureStudyPlanSeeded(forceReload = false) {
  await prisma.studyCourse.upsert({
    where: { id: 1 },
    update: {
      title: INITIAL_STUDY_COURSE.title,
      platform: INITIAL_STUDY_COURSE.platform,
      totalLessons: INITIAL_STUDY_COURSE.total_lessons,
      totalDurationMin: INITIAL_STUDY_COURSE.total_duration_min,
      totalSessions: INITIAL_STUDY_COURSE.total_sessions,
      daysOfWeek: INITIAL_STUDY_COURSE.schedule_config.days_of_week.join(","),
      targetDurationMin: INITIAL_STUDY_COURSE.schedule_config.target_duration_min,
      startDate: INITIAL_STUDY_COURSE.schedule_config.start_date,
      endDate: INITIAL_STUDY_COURSE.schedule_config.end_date,
    },
    create: {
      id: 1,
      title: INITIAL_STUDY_COURSE.title,
      platform: INITIAL_STUDY_COURSE.platform,
      totalLessons: INITIAL_STUDY_COURSE.total_lessons,
      totalDurationMin: INITIAL_STUDY_COURSE.total_duration_min,
      totalSessions: INITIAL_STUDY_COURSE.total_sessions,
      daysOfWeek: INITIAL_STUDY_COURSE.schedule_config.days_of_week.join(","),
      targetDurationMin: INITIAL_STUDY_COURSE.schedule_config.target_duration_min,
      startDate: INITIAL_STUDY_COURSE.schedule_config.start_date,
      endDate: INITIAL_STUDY_COURSE.schedule_config.end_date,
    },
  });

  const existingPlanSessionsCount = await prisma.studyTask.count({
    where: { sessionNumber: { not: null } },
  });

  if (existingPlanSessionsCount === 0 || forceReload) {
    if (forceReload) {
      await prisma.studyTask.deleteMany({
        where: { sessionNumber: { not: null } },
      });
    }

    const dataToCreate = INITIAL_STUDY_PLAN.map((s) => {
      const [y, m, d] = s.date.split("-").map(Number);
      const firstLesson = s.lessons[0]?.title || "";
      const lastLesson = s.lessons[s.lessons.length - 1]?.title || "";
      const summarySubject =
        s.lessons.length > 1
          ? `Jornada #${s.session}: ${firstLesson} → ${lastLesson}`
          : `Jornada #${s.session}: ${firstLesson}`;

      return {
        sessionNumber: s.session,
        date: new Date(Date.UTC(y, m - 1, d, 12, 0, 0)),
        dateStr: s.date,
        dayOfWeek: s.day,
        subject: summarySubject,
        totalMin: s.total_min,
        lessonsCount: s.lessons_count,
        lessons: JSON.stringify(
          s.lessons.map((l) => ({ ...l, completed: s.completed }))
        ),
        completed: s.completed,
      };
    });

    await prisma.studyTask.createMany({
      data: dataToCreate,
    });
  }
}
